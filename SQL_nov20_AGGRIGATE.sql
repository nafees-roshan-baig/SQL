SELECT * FROM SALES;
DESC SALES;

SELECT COUNT(*) AS TOTAL_PRODUCTS FROM SALES;

SELECT SUM(QUANTITY) AS TOTAL_QUANTITY FROM SALES;
SELECT AVG(PRICE) AS AVG_PRICE FROM SALES;
SELECT MIN(PRICE) AS MIN_PRICE FROM SALES;
SELECT MAX(PRICE) AS MAX_PRICE FROM SALES;
SELECT MIN(PRICE) AS MIN ,MAX(PRICE) AS MAX FROM SALES;

SELECT  CATEGORY, COUNT(*) AS TOTAL_PRODUCTS FROM SALES GROUP BY CATEGORY;
SELECT CATEGORY,SUM(QUANTITY) AS TOTAL_QTY FROM SALES GROUP BY CATEGORY;
SELECT CATEGORY , AVG(PRICE) AS AVG_PRICE FROM SALES GROUP BY CATEGORY;

SELECT CATEGORY , SUM(PRICE) AS TOTAL_AMOUNT FROM SALES GROUP BY CATEGORY HAVING TOTAL_AMOUNT > 10000;
SELECT CATEGORY , SUM(PRICE) AS TOTAL_PRICE FROM SALES GROUP BY CATEGORY ORDER BY TOTAL_PRICE DESC;\

