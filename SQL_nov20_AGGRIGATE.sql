CREATE DATABASE SALES_DB;
USE SALES_DB;

CREATE TABLE SALES(
SALE_ID INT PRIMARY KEY AUTO_INCREMENT,
PRODUCT_NAME VARCHAR(30),
CATEGORY VARCHAR(25),
QUANTITY INT,
PRICE DECIMAL(10,2)
);

